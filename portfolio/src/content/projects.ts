import data from "./data/projects.json";
import type { Locale, Project } from "./types";

/** Text that changes with the language; everything else in an entry is shared by both. */
type ProjectText = Pick<Project, "tag" | "title" | "dek" | "result" | "alt" | "client">;

/**
 * One project as stored in data/projects.json, which the editor at admin.hgsportafolio.site writes. The editor may
 * leave optional fields as "" or null, so every optional value is normalized before it reaches the components.
 */
export interface ProjectEntry {
  id: string;
  /** Kept in the file but left off the site. */
  hidden?: boolean | null;
  featured?: boolean | null;
  /** My own product: a band of its own before the client grid. */
  own?: boolean | null;
  href?: string | null;
  /** Id of the case study page (e.g. "aria"), when the project has one. */
  case?: string | null;
  /** Public repository. Only for code that is mine to publish, never a client's. */
  code?: string | null;
  /** Download page of an own product that is an app. */
  download?: string | null;
  offline?: boolean | null;
  shot?: string | null;
  clientHref?: string | null;
  institutional?: boolean | null;
  logo?: string | null;
  hue?: number | null;
  stack?: readonly string[] | null;
  es: Partial<Record<keyof ProjectText, string | null>> & { points?: readonly string[] | null };
  en: Partial<Record<keyof ProjectText, string | null>> & { points?: readonly string[] | null };
}

const text = (v: string | null | undefined) => v?.trim() || undefined;

/**
 * Screenshots are served as public/shots/<name>.webp, generated by `npm run images` from the original the editor
 * uploads to images/shots/. Whatever extension or folder the entry stores, the card points at the WebP.
 */
const shotPath = (v: string | null | undefined) => {
  const name = text(v)
    ?.split("/")
    .pop()
    ?.replace(/\.[a-z0-9]+$/i, "");
  return name ? `shots/${name}.webp` : undefined;
};

/** Visible projects for a language, in the order given. Absent optional values stay absent. */
export function projectsFrom(entries: readonly ProjectEntry[], locale: Locale): Project[] {
  return entries
    .filter((p) => !p.hidden)
    .map((p) => {
      const t = p[locale];
      const project: Project = {
        id: p.id,
        tag: text(t.tag) ?? "",
        title: text(t.title) ?? "",
        dek: text(t.dek) ?? "",
        result: text(t.result) ?? "",
        stack: (p.stack ?? []).map((s) => s.trim()).filter(Boolean),
        shot: shotPath(p.shot),
        alt: text(t.alt),
        href: text(p.href),
        codeHref: text(p.code),
        caseHref: text(p.case) ? `${locale === "en" ? "/en" : ""}/${text(p.case)}/` : undefined,
        offline: p.offline || undefined,
        client: text(t.client),
        clientHref: text(p.clientHref),
        institutional: p.institutional || undefined,
        logo: text(p.logo),
        hue: typeof p.hue === "number" ? p.hue : undefined,
        featured: p.featured || undefined,
        own: p.own || undefined,
        points: t.points?.length ? t.points.map((s) => s.trim()).filter(Boolean) : undefined,
        downloadHref: text(p.download),
      };
      // Drop undefined keys so the objects match the hand-written ones the components were built against.
      return Object.fromEntries(Object.entries(project).filter(([, v]) => v !== undefined)) as unknown as Project;
    });
}

/** Projects of the site for a language, from data/projects.json. */
export const projectsFor = (locale: Locale) => projectsFrom((data as { projects: ProjectEntry[] }).projects, locale);
